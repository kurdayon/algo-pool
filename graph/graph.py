class Graph:

	def __init__(self, names, graph):
		'''
		Graph is given in the format generated by the "get_rand_graph" function.
		'''
		self.names = names
		self.graph = graph
		self.fname2func = {
			'add' : Add(),
			'subtract' : Subtract(),
			'mul' : Multiply(),
			'divide' : Divide(),
			'power': Power(),
			'exp' : Exp(),
			'log' : Log(),
			'tanh' : Tanh(),
			'smif' : Smif(),

			'max' : Max(),
			'min' : Min(),

			#'A' : A(),
			#'O' : O(),
			#'X' : X(),
			##'L' : L(),
			#'R' : R(),
			#'M' : M(),
			#'N' : N(),
			}

	#---------------------------------------------------------------------------

	def get_node2val(self, node2val, calc_grads = False):
		'''
		Takea a dict mappint argument- and constant-names into their values.
			For example: {'x1':1.2, 'x2':3.7, 'c1':5.4, 'c2':0.7, 'c3':3.7}
		Extends the input dictionary by adding mapping from hidden and output nodes to their values.
		'''

		grads = []
		for i in range(len(self.graph)):
			fname     = self.graph[i][0]
			arg_names = self.graph[i][1:]
			arg_vals = [node2val[arg_name] for arg_name in arg_names]
			func = self.fname2func[fname]
			fval = func.get_value(*arg_vals)
			node2val[self.names[i]] = fval

			# get the values of the gradients.
			if calc_grads:
				grad = func.get_grads(*arg_vals)
				grads.append(grad[:])

		return node2val, grads

	#def get_node2grads(self, node2grads):

	#---------------------------------------------------------------------------

	def back(self, node2val, grads):
		'''
		It takes a dictionary mapping outputs to gradients and generates gradients for all nodes.
		'''
		for i in range(len(self.graph)):
			j = -(i + 1)
			g = self.graph[j]
			name = self.names[j]
			for k in range(len(g[1:])):
				arg_name = g[k+1]
				update = node2val[self.names[j]] * grads[j][k]
				try:
					node2val[arg_name] += update
				except KeyError:
					node2val[arg_name]  = update
		return node2val

	#---------------------------------------------------------------------------

	def seq_eval(self, Xs, cs, h_ini):
		'''
		Treats the graphs as a recurrent system.
		'''
		node2val_list = []
		grads_list = []
		n_steps, x_dim = Xs.shape
		n_hid = len(h_ini)
		n_consts = len(cs)
		for step_ind in range(n_steps):
			node2val = {}

			# sepecify values of the constants
			for i in range(n_consts):
				node2val['c'+str(i+1)] = cs[i]

			# recurrency step (to bind the steps)
			if step_ind > 0:
				for i in range(n_hid):
					node2val['x'+str(i+1)] = node2val_list[step_ind-1]['o'+str(i+1)]
			else:
				for i in range(n_hid):
					node2val['x'+str(i+1)] = h_ini[i]

			# bind the external input
			for i in range(x_dim):
				node2val['x'+str(i + n_hid + 1)] = Xs[step_ind, i]

			node2val, grads = self.get_node2val(node2val, calc_grads = True)
			node2val_list.append(node2val)
			grads_list.append(grads)

		return node2val_list, grads_list

	#---------------------------------------------------------------------------

	def seq_back(self, node2val_list, grads_list, h_dim):
		'''
		Returns derivatives over inputs of the recurrent model.
		'''
		out = []
		n_steps = len(grads_list)
		for i in range(n_steps):
			j = -(i+1)
			node2val_list[j] = self.back(node2val_list[j], grads_list[j])
			# recurrency
			if i + 1 != n_steps:
				for k in range(h_dim):
					node2val_list[j-1]['o'+str(k+1)] = node2val_list[j]['x'+str(k+1)]

		return node2val_list


