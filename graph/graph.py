'''
	Class that represents functions given by DAGs (directed acyclic graphs).
	The functions, given as DAGs, can be evaluated (forward algorithm).
	Backpropagation is also supported.

	Q & A:
		1. Is there a convetion for names (should start with 'x' or 'c') ?
		   In "eval" and "back" no assumptions about the node names is used.
		   In the "seq_eval" and "seq_back" we rely on the name convention.

		2. Are 'xs' treated differently from 'cs' ?
		   Not in "val" and "back" (but in "seq_eval" and "seq_back").

		3. Do we have gradiens with respect to the indirect inputs to nodes ?
		4. What if a graph inconsisten (contains loops, or uses variables that are note defined) ?
		5. Can output node be used as input to another node ?

	Usage (see __main__ part of the code):

		* At instantiation we need to give two arguments: (1) names, (2) graph.
		* "names" - a list of varaible names. For example: ['h1', 'h2', 'o1']
		  	We need to give only those variables that are calculated (so, not input 'xs' and not constants 'cs')
		* "graph" - a list of lists specifying how variables should be calculated. For exmample:
		  	[['multiply','x1','c1'], ['multiply','x2','x2'], ['add','h1','h2']]
		  	Each element of the list corresponds to the corresponding vairable from the "names".
		* These two inputs can be either prepared manually of generated by the "get_rand_graph" function.

		* After an graph-instance is created, it can be evaluated on a given input (represented by a dictionary):
			y, grads = g.eval({'x1':x1, 'x2':x2, 'c1':c1})
			In this dictionary all the values should be numpy arrays of the same shape.
		* The output is a dictionary mapping all variables (hidden, output as well as inputs and constants) to their values.
		* In addition to the value of the above described graph nodes, we can get "gradients" as a list of lists.
			The gradiens are returned only if "calc_grads" argument of the "eval" method is set to True.
			Each ellement of the gradiens-list corresponds to a variable (from "names") and is a list itself,
			containing derivatives of the considered variable with respect to its input nodes.
			The vaues of the gradients are calculated at the values of input.
			The "gradietns-list" is used as input for the backpropagation.

		* We can evaluate graph on a sequence.
		* The interface for calling this method is: g.seq_eval(Xs, cs, h_ini)
		* "Xs" is 2D array with rows (axis 0) corresponding to the time steps.
		* "cs" is a list with numerical values: [c1, c2, ..., cn]
		* "h_ini" initial values of the hidden variables (in the recurrent sence, not of the graph).
		* The hidden vectors are given as first arguments of the graph, then we give values from Xs.
		* The first outputs of the graphs are treated as new hiden vector, the rest is just saved.
		* The first output of the method is a list of dictionaries mapping variables to their values for each step.
		* Then we have the list of gradients.
'''

import numpy as np

#-------------------------------------------------------------------------------

class Add:

	def get_value(self, x1, x2):
		return np.add(x1, x2)

	def get_grads(self, x1, x2):
		return [1.0 + 0.0*x1, 1.0 + 0.0*x2]

class Multiply:

	def get_value(self, x1, x2):
		return np.multiply(x1, x2)

	def get_grads(self, x1, x2):
		return [x2, x1]

class Max:

	def get_value(self, x1, x2):
		return np.maximum(x1, x2)

	def get_grads(self, x1, x2):
		return [np.where(x1 > x2, 1, 0), np.where(x1 < x2, 0, 1)]

class Min:

	def get_value(self, x1, x2):
		return np.minimum(x1, x2)

	def get_grads(self, x1, x2):
		return [np.where(x1 > x2, 0, 1), np.where(x1 < x2, 1, 0)]

class Exp:

	def get_value(self, x):
		return np.exp(x)

	def get_grads(self, x):
		return np.exp(x)

