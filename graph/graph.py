class Power:
	def get_value(self, x1, x2):
		return np.sign(x1) * np.power(np.abs(x1), x2)

class Log:
	def get_value(self, x1):
		return np.sign(x1) * np.log(np.abs(x1))

class Tanh:
	def get_value(self, x1):
		return np.tanh(x1)

class Smif:
	def get_value(self, x1, x2, x3):
		w = (np.tanh(x2) + 1.0) / 2.0
		return x1 * (1.0 - w) + x2 * w

