	from get_rand_graph import get_rand_graph

	n_inp, n_con, n_hid, n_out = 3, 2, 4, 1
	funcs = [('add',2), ('mul',2), ('exp',1), ('log',1), ('smif',3)]

	names, graph, n_consts = get_rand_graph(n_inp, n_con, n_hid, n_out, funcs)
	print('Original:')
	for name, node in zip(names, graph):
		print('   ' + name + ' = ' + str(node))

	for step in range(4):
		names, graph, n_consts, info = mutate_graph(names, graph, n_inp, n_con, funcs)
		print('')
		print('Mutation: ' + str(info))
		for name, node in zip(names, graph):
			print('   ' + name + ' = ' + str(node))

	# Stress test: long chains of mutations on random graphs. Every graph must stay valid.
	counts = {}
	n_steps = 0
	for trial in range(1000):
		random.seed(trial)
		n_inp, n_con = random.randint(1, 4), random.randint(0, 3)
		names, graph, n_consts = get_rand_graph(n_inp, n_con, random.randint(0, 6), random.randint(1, 3), funcs)
		for step in range(30):
			old = (names[:], [node[:] for node in graph])
			new_names, new_graph, n_consts, info = mutate_graph(names, graph, n_inp, n_con, funcs)
			assert (names, graph) == old, 'the input must not be changed'
			assert (new_names, new_graph) != old, 'the mutated graph must be different'
			check_graph(new_names, new_graph, n_inp, n_consts, funcs)
			counts[info['type']] = counts.get(info['type'], 0) + 1
			names, graph = new_names, new_graph
			n_steps += 1
	print('')
	print('Stress test passed: ' + str(n_steps) + ' mutations, all graphs stayed valid.')
	print('Mutation kinds: ' + str(counts))
