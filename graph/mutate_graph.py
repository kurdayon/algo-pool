'''
	Just run the script in the command line to see an example of how it works!
	Here we make one random change (mutation) in a "graph" given in the format
	generated by the "get_rand_graph" function (see "get_rand_graph.py") and
	executed by the code in the "graph.py" file.

	The mutated graph keeps all the conventions of the original one:
		1. Each node uses only inputs, constants and hidden nodes that come before it.
		2. Each hidden node is used by at least one later node (hidden or output).
		3. No node uses only constants as arguments.
		4. Hidden nodes are called h1, h2, ... (in the order of the list), then the outputs follow.
		5. The used constants are called c1, c2, ... (without gaps).

	There are four kinds of mutations:

		'change_op'   - The function of one node is replaced by another function.
						If the new function needs fewer arguments, some of the old
						arguments are dropped. If it needs more, new ones are added.

		'change_arg'  - One argument of one node is replaced by another input,
						constant or earlier hidden node.

		'add_node'    - A new hidden node is inserted "into a connection": we take
						one argument of one node (say node B uses A), create
						a new node N that uses A (and maybe something else)
						and let B use N instead of A. This way A stays used
						and the new node is used from the start.

		'remove_node' - One hidden node is removed. Every node that used it gets
						one of the arguments of the removed node instead
						(the removed node is "bypassed").
						Output nodes are never added or removed.

	A change is accepted only if the result satisfies the conventions above.
	If the chosen change is not possible, another one is tried.
'''

import random
from itertools import combinations

def _is_const(arg):
	return arg.startswith('c')

def _is_hid(arg):
	return arg.startswith('#')

def _is_valid(toks, nodes):
	'''
	Checks the conventions 1-3 (see the top of the file).
	Here the hidden nodes are called by temporary names starting with '#'.
	'''
	seen = set()
	used = set()
	for tok, node in zip(toks, nodes):
		args = node[1:]
		if len(args) == 0 or all(_is_const(a) for a in args):
			return False
		for a in args:
			if _is_hid(a):
				if a not in seen:
					return False
				used.add(a)
		if _is_hid(tok):
			seen.add(tok)
	return used == seen

def mutate_graph(names, graph, n_inp, n_con, funcs, kinds = None, seed = None):
	'''
	Arguments:
		names - list of node names, for example: ['h1', 'h2', 'h3', 'o1', 'o2']
		graph - list of nodes, for example: [['add', 'x1', 'c1'], ['mul', 'h1', 'x2'], ...]
		n_inp - number of input nodes (x1, x2, ...) that the graph is allowed to use.
		n_con - the largest number of constants that the graph is allowed to use.
		funcs - a list of possible functions as tuples ('func_name', n_args).
		kinds - a list of allowed mutation kinds. By default all four are allowed:
				['change_op', 'change_arg', 'add_node', 'remove_node']
		seed  - seed for the random numbers (optional, to get the same mutation again).

	Output:
		Four values: "names", "graph", "n_consts", "info".
		names, graph, n_consts - the mutated graph, in the same form as returned by "get_rand_graph".
		info - a dictionary that describes what has been done:
			'type'      - kind of the mutation (one of the four above).
			'node'      - name of the changed or added node (in the new graph),
						or of the removed node (in the old graph).
			'const_map' - maps old names of the constants to the new ones, for example {'c1':'c1', 'c3':'c2'}.
						A constant that is not used anymore is not in the map.
			'new_const' - name of a constant that was not in the old graph (or None).

	The input lists are not changed.
	Raises ValueError if no mutation of the allowed kinds is possible.
	'''

	rng = random if seed is None else random.Random(seed)
	if kinds is None:
		kinds = ['change_op', 'change_arg', 'add_node', 'remove_node']

	# The hidden nodes get temporary names ('#0', '#1', ...), which do not depend on the position.
	# This way we do not need to rename anything while we insert or remove nodes.
	n_hid = len([name for name in names if name.startswith('h')])
	name2tok = dict([(names[i], '#' + str(i)) for i in range(n_hid)])
	toks = [name2tok.get(name, name) for name in names]
	nodes = [[node[0]] + [name2tok.get(a, a) for a in node[1:]] for node in graph]

	xs = ['x' + str(i + 1) for i in range(n_inp)]
	cs = list(set([a for node in nodes for a in node[1:] if _is_const(a)]))
	cs.sort(key = lambda c: int(c[1:]))
	old_cs = cs[:]
	# 'c*' stands for a constant which is not used yet.
	if len(cs) < n_con:
		cs = cs + ['c*']

	def copy(nodes):
		return [node[:] for node in nodes]

	def options(pos):
		# everything that can be used as an argument by the node at the position "pos"
		return xs + cs + [t for t in toks[:pos] if _is_hid(t)]

	def all_slots():
		# all the arguments of all the nodes as pairs (node_ind, arg_ind), in a random order
		slots = [(i, k) for i in range(len(nodes)) for k in range(1, len(nodes[i]))]
		rng.shuffle(slots)
		return slots

	def n_uses(arg):
		return len([a for node in nodes for a in node[1:] if a == arg])

	def shuffled(vals):
		vals = list(vals)
		rng.shuffle(vals)
		return vals

	#---------------------------------------------------------------------------

	def change_op():
		for i in shuffled(range(len(nodes))):
			old_args = nodes[i][1:]
			for fname, n_args in shuffled(funcs):
				if fname == nodes[i][0]:
					continue
				if n_args <= len(old_args):
					# keep some of the old arguments (in the old order)
					cands = [list(c) for c in combinations(old_args, n_args)]
					cands = shuffled(cands)
				else:
					extra = [rng.choice(options(i)) for k in range(n_args - len(old_args))]
					cands = [old_args + extra]
				for args in cands:
					new_nodes = copy(nodes)
					new_nodes[i] = [fname] + args
					if _is_valid(toks, new_nodes):
						return toks, new_nodes, toks[i]
		return None

	def change_arg():
		for i, k in all_slots():
			for val in shuffled(options(i)):
				if val == nodes[i][k]:
					continue
				# replacing the only use of a constant by a new constant would give the same graph
				if val == 'c*' and _is_const(nodes[i][k]) and n_uses(nodes[i][k]) == 1:
					continue
				new_nodes = copy(nodes)
				new_nodes[i][k] = val
				if _is_valid(toks, new_nodes):
					return toks, new_nodes, toks[i]
		return None

	def add_node():
		for i, k in all_slots():
			# the node "i" uses "val". The new node will stay between them.
			val = nodes[i][k]
			lo = toks.index(val) + 1 if _is_hid(val) else 0
			hi = min(i, n_hid)
			pos = rng.randint(lo, hi)
			for fname, n_args in shuffled(funcs):
				for attempt in range(5):
					args = [rng.choice(options(pos)) for j in range(n_args)]
					args[rng.randrange(n_args)] = val
					new_nodes = copy(nodes)
					new_nodes[i][k] = '#new'
					new_nodes.insert(pos, [fname] + args)
					new_toks = toks[:pos] + ['#new'] + toks[pos:]
					if _is_valid(new_toks, new_nodes):
						return new_toks, new_nodes, '#new'
		return None

	def remove_node():
		for i in shuffled(range(n_hid)):
			tok = toks[i]
			args = nodes[i][1:]
			slots = [(j, k) for j, k in all_slots() if nodes[j][k] == tok]
			for attempt in range(20):
				# Each user of the removed node gets one of its arguments.
				# First we try to give each argument to somebody (so that it stays used).
				first = shuffled(set(args))
				new_nodes = copy(nodes)
				for s in range(len(slots)):
					j, k = slots[s]
					new_nodes[j][k] = first[s] if s < len(first) else rng.choice(args)
				del new_nodes[i]
				new_toks = toks[:i] + toks[i+1:]
				if _is_valid(new_toks, new_nodes):
					return new_toks, new_nodes, tok
				rng.shuffle(slots)
		return None

	#---------------------------------------------------------------------------

	kind2func = {'change_op':change_op, 'change_arg':change_arg, 'add_node':add_node, 'remove_node':remove_node}
	res = None
	for kind in shuffled(set(kinds)):
		res = kind2func[kind]()
		if res is not None:
			break
	if res is None:
		raise ValueError('no valid mutation exists for this graph')
	new_toks, new_nodes, node_tok = res

	# give the final names to the hidden nodes (h1, h2, ...)
	hid_toks = [t for t in new_toks if _is_hid(t)]
	tok2name = dict([(hid_toks[i], 'h' + str(i + 1)) for i in range(len(hid_toks))])

	# give the final names to the constants (c1, c2, ... without gaps). The new constant is the last one.
	used = set([a for node in new_nodes for a in node[1:] if _is_const(a)])
	used_cs = [c for c in old_cs if c in used]
	const_map = dict([(used_cs[i], 'c' + str(i + 1)) for i in range(len(used_cs))])
	new_const = None
	if 'c*' in used:
		new_const = 'c' + str(len(used_cs) + 1)
		tok2name['c*'] = new_const
	n_consts = len(used)

	tok2name.update(const_map)
	new_names = [tok2name.get(t, t) for t in new_toks]
	new_graph = [[node[0]] + [tok2name.get(a, a) for a in node[1:]] for node in new_nodes]

	info = {
		'type' : kind,
		'node' : names[toks.index(node_tok)] if kind == 'remove_node' else tok2name.get(node_tok, node_tok),
		'const_map' : const_map,
		'new_const' : new_const,
		}
	return new_names, new_graph, n_consts, info

#-------------------------------------------------------------------------------

def check_graph(names, graph, n_inp, n_consts, funcs):
	'''
	Raises AssertionError if the graph does not follow the conventions
	listed at the top of the file. Used for testing.
	'''
	fname2n = dict(funcs)
	n_hid = len([name for name in names if name.startswith('h')])
	assert len(names) == len(graph)
	assert names[:n_hid] == ['h' + str(i + 1) for i in range(n_hid)]
	assert all(name.startswith('o') for name in names[n_hid:])
	xs = ['x' + str(i + 1) for i in range(n_inp)]
	cs = ['c' + str(i + 1) for i in range(n_consts)]
	used = set()
	for i in range(len(graph)):
		args = graph[i][1:]
		assert len(args) == fname2n[graph[i][0]]
		assert all(a in xs + cs + names[:min(i, n_hid)] for a in args)
		assert any(not a.startswith('c') for a in args)
		used.update(args)
	assert all(name in used for name in names[:n_hid])
	assert all(c in used for c in cs)

